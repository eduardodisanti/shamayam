#!/usr/bin/env python3
"""
Generate the LaTeX tables of Section 9 from `results/data.json`.

WHY THE TABLES ARE GENERATED
----------------------------
Every number in the results section was previously copied by hand from a text
report into a `tabular`. That is the step at which a paper silently goes stale:
a seed changes, the run is repeated, and the prose no longer matches the code.
Generating the tables removes the step. The paper inputs them, so recompiling
after a fresh run updates the numbers with no human in the loop.

Each emitted file carries a provenance header naming the run it came from, so
a table that was not regenerated is visible as such in the source.

    python3 make_tables.py          # -> tables/*.tex

The prose around the tables still quotes numbers inline, and that prose is NOT
generated; it remains the one place where a value can go stale unnoticed.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
DATA_PATH = HERE / "results" / "data.json"
TABDIR = HERE.parent / "tables"


PLACEHOLDER = r"""\begin{{table}}[htbp]
\centering
\fbox{{\begin{{minipage}}{{0.9\linewidth}}\centering\vspace{{4pt}}
\textbf{{NOT GENERATED}}\\[2pt]
{what} requires layer A2. Run
\texttt{{python3 run\_all.py}} then \texttt{{python3 make\_tables.py}}.
\vspace{{4pt}}\end{{minipage}}}}
\caption{{Placeholder for \texttt{{{key}}}; regenerate before submission.}}
\label{{tab:{key}}}
\end{{table}}
"""


def _header(meta, label):
    return (f"% GENERATED by experiments/make_tables.py -- do not edit.\n"
            f"% source: results/data.json, run {meta.get('generated_utc','?')}"
            f", seed {meta.get('seed','?')}"
            + ("  [QUICK RUN, not quotable]" if meta.get("quick") else "")
            + f"\n% regenerate: python3 run_all.py && python3 make_tables.py\n"
            f"% label: {label}\n")


def _write(name, body, meta, label):
    TABDIR.mkdir(exist_ok=True)
    path = TABDIR / f"{name}.tex"
    path.write_text(_header(meta, label) + body)
    print(f"  wrote {path.relative_to(HERE.parent)}")


# ---------------------------------------------------------------------

def table_arms(d, meta):
    a = d["arms"]
    rows = []
    for r in a["by_distribution"]:
        far = r["far"]
        rows.append(f"{r['distribution']} & " +
                    " & ".join(f"{far[t]:.2f}" for t in ("A1", "A2", "A3", "A4")) +
                    f" & {r['median_n_A1']:.0f} \\\\")
    cov, se = a["pooled_coverage"], a["pooled_se"]
    body = f"""\\begin{{table}}[htbp]
\\centering
\\caption{{Out-of-sample false-alarm rate (\\%) by arm and residual
distribution, nominal level {100*a['alpha']:.1f}\\%. A1 reproduces the published
pipeline; A4 is the configuration to which
Proposition~\\ref{{prop:coverage}} applies without qualification. The last
column is the median commissioning length selected by the adaptive rule in
arm~A1.}}
\\label{{tab:arms}}
\\begin{{tabular}}{{lrrrrr}}
\\toprule
Residual distribution & A1 & A2 & A3 & A4 & med.\\ $n$ (A1) \\\\
\\midrule
{chr(10).join(rows)}
\\midrule
pooled coverage & """ + " & ".join(f"{cov[t]:.5f}" for t in ("A1","A2","A3","A4")) + """ & \\\\
(standard error) & """ + " & ".join(f"({se[t]:.5f})" for t in ("A1","A2","A3","A4")) + """ & \\\\
pooled FAR (\\%) & """ + " & ".join(f"{100*(1-cov[t]):.2f}" for t in ("A1","A2","A3","A4")) + """ & \\\\
\\bottomrule
\\end{tabular}
\\end{table}
"""
    _write("arms", body, meta, "tab:arms")


def table_variance(d, meta):
    rows = [f"{r['n']} & {r['k_alpha']} & {'yes' if r['is_max'] else 'no'} & "
            f"{r['sd']:.4f} \\\\" for r in d["variance"]]
    body = f"""\\begin{{table}}[htbp]
\\centering
\\caption{{Standard deviation of the certified radius against commissioning
length, on a lognormal residual stream. Inside the degenerate range of
Corollary~\\ref{{cor:degenerate_range}} the estimator is the sample maximum and
its dispersion is essentially constant; it contracts only once an interior
order statistic becomes available.}}
\\label{{tab:variance}}
\\begin{{tabular}}{{rrlr}}
\\toprule
$n$ & $k_\\alpha$ & sample max? & $\\mathrm{{sd}}(\\tau)$ \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""
    _write("variance", body, meta, "tab:variance")


def table_exchangeability(d, meta):
    rows = []
    for r in d["exchangeability"]["rows"]:
        p = r["power"]
        rows.append(f"{r['distribution']} & {r['size']:.3f} & " +
                    " & ".join(f"{p[k]:.3f}" for k in ("0.5", "1.0", "2.0", "3.0"))
                    + " \\\\")
    body = f"""\\begin{{table}}[htbp]
\\centering
\\caption{{Rejection rate of the permutation test at level $0.05$. The first
column is the size, measured on exchangeable streams; the remainder is the
power against an injected monotone drift, in standard deviations of
accumulated trend.}}
\\label{{tab:exchangeability}}
\\begin{{tabular}}{{lrrrrr}}
\\toprule
Residual distribution & size & drift 0.5 & drift 1.0 & drift 2.0 & drift 3.0 \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""
    _write("exchangeability", body, meta, "tab:exchangeability")


def table_saturation(d, meta):
    s = d["saturation"]
    rows = []
    for r in s["rows"]:
        if r["certified_mean"] is None:
            rows.append(f"{r['n']} & -- & -- & -- & -- & -- & "
                        f"{r['interpolated_mean']:.3f} & "
                        f"{r['interpolated_coverage']:.4f} & -- \\\\")
        else:
            rows.append(
                f"{r['n']} & {r['certified_mean']:.3f} & {r['certified_sd']:.3f} & "
                f"${r['bias_pct']:+.2f}$ & {r['coverage']:.4f} & "
                f"{r['coverage_theory']:.4f} & "
                f"{r['interpolated_mean']:.3f} & "
                f"{r['interpolated_coverage']:.4f} & "
                f"{'yes' if r['is_max'] else 'no'} \\\\")
    body = f"""\\begin{{table}}[htbp]
\\centering
\\caption{{Saturation of the nominal radius against the reference
$R_p={s['R_pop']:.3f}$. ``certified'' is the estimator of
Corollary~\\ref{{cor:saturation_certification}}, ``interp'' the interpolated
empirical quantile. ``exact'' is the coverage predicted by
Proposition~\\ref{{prop:coverage}}, $k_\\alpha/(n+1)$; the observed certified
coverage matches it to within {s.get('max_abs_z', float('nan')):.1f} Monte Carlo
standard errors at every $n$, including the non-trivial values taken inside the
degenerate range. The interpolated estimator undercovers throughout. A dash
marks a commissioning length below the floor, at which no radius is
certifiable.}}
\\label{{tab:saturation}}
\\setlength{{\\tabcolsep}}{{4pt}}\\small
\\begin{{tabular}}{{rrrrrrrrl}}
\\toprule
$n$ & certified & sd & bias (\\%) & coverage & exact & interp & int.\\ cov & max? \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""
    _write("saturation", body, meta, "tab:saturation")


def table_dimension(d, meta):
    rows = [f"{r['parameters']} & {r['predicted']} & {r['k10']:.2f} & "
            f"{r['k20']:.2f} & {r['k40']:.2f} \\\\"
            for r in d["dimension"]["tracking"]]
    body = f"""\\begin{{table}}[htbp]
\\centering
\\caption{{Maximum-likelihood intrinsic dimension of the noise-free nominal
family, against the number of active nuisance parameters. The estimator is
biased downward, increasingly so with dimension, so the criterion is whether
it \\emph{{tracks}} the prediction rather than whether it matches it. Ambient
dimension is {d['dimension']['ambient']}.}}
\\label{{tab:dimension}}
\\begin{{tabular}}{{lrrrr}}
\\toprule
active nuisance parameters & predicted & $k=10$ & $k=20$ & $k=40$ \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""
    _write("dimension", body, meta, "tab:dimension")


def table_adequacy(d, meta):
    rows = []
    for op in d["adequacy"]["operators"]:
        name = op["operator"].split("(")[0].strip()
        ball = op["detection"].get("ball_fault", float("nan"))
        rows.append(
            f"{name} & {op['healthy_far']:.1f} & {ball:.0f} & "
            f"${op['max_accepted_distance']:.3g}$ & "
            f"${op['ratio']:.1f}\\times$ & "
            f"{'pass' if op['passes'] else 'fail'} \\\\")
    scale = d["adequacy"]["operators"][0]["nominal_scale"]
    body = f"""\\begin{{table}}[htbp]
\\centering
\\caption{{Distance-proxy probe. Latent codes are pushed away from the nominal
range, decoded, and the residual compared against the true distance to a
disjoint nominal cloud, whose median nearest-neighbour spacing is
{scale:.2f}. Both operators attain the calibrated coverage; they differ by
more than two orders of magnitude in what they accept.}}
\\label{{tab:adequacy}}
\\setlength{{\\tabcolsep}}{{5pt}}
\\begin{{tabular}}{{lrrrrl}}
\\toprule
operator & healthy FAR & ball DR & max accepted & ratio to & adequacy \\\\
         & (\\%)        & (\\%)    & distance     & spacing  &          \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""
    _write("adequacy", body, meta, "tab:adequacy")


TABLES = [
    ("arms", table_arms, "arms"),
    ("variance", table_variance, "variance"),
    ("exchangeability", table_exchangeability, "exchangeability"),
    ("saturation", table_saturation, "saturation"),
    ("dimension", table_dimension, "dimension"),
    ("adequacy", table_adequacy, "adequacy"),
]


def main():
    if not DATA_PATH.exists():
        raise SystemExit(f"{DATA_PATH} not found; run `python3 run_all.py` first")
    d = json.loads(DATA_PATH.read_text())
    meta = d.get("_meta", {})
    if meta.get("quick"):
        print("WARNING: data.json came from a --quick run; the tables it "
              "produces are not quotable.")

    written, skipped = 0, []
    for key, fn, needs in TABLES:
        if needs not in d:
            # A missing table must not break the build. Emitting a visible
            # placeholder keeps the document compilable and makes the gap
            # obvious in the PDF, which is safer than either a hard failure or
            # a silently stale table left over from an earlier run.
            _write(key, PLACEHOLDER.format(
                what=f"Table `{key}`", key=key), meta, f"tab:{key}")
            skipped.append(key)
            continue
        fn(d, meta)
        written += 1

    if skipped:
        print(f"  placeholders emitted (absent from data.json): "
              f"{', '.join(skipped)}")
        print("  run `python3 run_all.py` with layer A2 to fill them")
    print(f"{written} table(s) written to {TABDIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
