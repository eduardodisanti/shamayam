#!/usr/bin/env python3
"""
Emit `tables/values.tex`: the numbers the PROSE quotes, as LaTeX macros.

WHY THIS EXISTS
---------------
`make_tables.py` closed the gap between the code and the tables, and
`make_figures.py` closed it for the figures. The docstring of the former
admitted what remained open:

    The prose around the tables still quotes numbers inline, and that prose is
    NOT generated; it remains the one place where a value can go stale
    unnoticed.

That is not a hypothetical. A sentence reading "coverage falls to 0.9788"
survives a re-run that moves the value to 0.9805, and nothing in the build
complains, because LaTeX cannot tell a stale digit from a fresh one. The
failure is silent and it is in the argument, not in an appendix.

This script removes the last hand-copied numbers by emitting a `\\newcommand`
for each. The paper says `\\satBiasHi` where it used to say `6.43`, so a
regenerated run propagates into the sentence as well as into the table. If a
macro is undefined the document fails to compile, which is the desired
behaviour: an unavailable number should stop the build rather than silently
retain an old one.

    python3 make_macros.py          # -> tables/values.tex

SCOPE. Only quantities that (i) appear inline in the prose and (ii) are
produced by `run_all.py` are emitted. Quantities fixed by the design -- the
target level, the commissioning floor, the degenerate range -- are theory, not
measurement, and stay written out in the text where the reader can check them
against the propositions.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
DATA_PATH = HERE / "results" / "data.json"
OUT = HERE.parent / "tables" / "values.tex"


class Macros:
    """
    Collector that refuses to emit a macro twice under different values, and
    records the section each macro came from so an absent section produces an
    absent macro rather than a plausible-looking wrong one.
    """

    def __init__(self):
        self._m = {}

    def add(self, name, value, fmt="{:.2f}"):
        text = fmt.format(value) if not isinstance(value, str) else value
        if name in self._m and self._m[name] != text:
            raise ValueError(f"macro {name} redefined: "
                             f"{self._m[name]!r} -> {text!r}")
        self._m[name] = text
        return text

    def render(self, meta):
        lines = [
            "% GENERATED by experiments/make_macros.py -- do not edit.",
            f"% source: results/data.json, run {meta.get('generated_utc','?')}"
            f", seed {meta.get('seed','?')}"
            + ("  [QUICK RUN, not quotable]" if meta.get("quick") else ""),
            "% regenerate: python3 run_all.py && python3 make_macros.py",
            "%",
            "% Each macro below is a measured quantity quoted inline in the",
            "% prose. An undefined macro is a compile error by design.",
            "",
        ]
        for name in sorted(self._m):
            lines.append(f"\\newcommand{{\\{name}}}{{{self._m[name]}}}")
        return "\n".join(lines) + "\n"


def _row(rows, n):
    for r in rows:
        if r["n"] == n:
            return r
    raise KeyError(f"no row at n={n}")


def saturation(d, m):
    s = d["saturation"]
    rows = s["rows"]
    lo, hi = s["degenerate_range"]

    m.add("satRefWindows", s.get("reference_windows", 0), "{:d}")
    m.add("satEvalBlock", s.get("eval_block", 0), "{:d}")
    m.add("satReps", s.get("reps", 0), "{:d}")
    # R_p itself is deliberately NOT emitted: the generated caption of
    # Table~\ref{tab:saturation} already carries it, and a second copy in the
    # prose would be one more place for the two to disagree.

    # Bias inside the degenerate range, and the discontinuity at its exit.
    m.add("satBiasLo", _row(rows, lo)["bias_pct"], "{:.2f}")
    m.add("satBiasHi", _row(rows, hi)["bias_pct"], "{:.2f}")
    m.add("satBiasDrop", _row(rows, hi + 1)["bias_pct"], "{:.2f}")

    # Interpolated coverage at the ends of the grid.
    first, last = rows[0], rows[-1]
    m.add("satInterpFirstN", first["n"], "{:d}")
    m.add("satInterpFirstCov", first["interpolated_coverage"], "{:.3f}")
    m.add("satInterpLastN", last["n"], "{:d}")
    m.add("satInterpLastCov", last["interpolated_coverage"], "{:.3f}")

    # Agreement with the exact coverage, which is the sharper claim than the
    # inequality and therefore the one the prose should make.
    if "max_abs_z" in s:
        m.add("satMaxZ", s["max_abs_z"], "{:.1f}")
    cert = [r for r in rows if r.get("coverage_theory") is not None]
    if cert:
        m.add("satExactAtDegHi",
              _row(cert, hi)["coverage_theory"], "{:.4f}")
        m.add("satCovAtDegHi", _row(cert, hi)["coverage"], "{:.4f}")

    # Plug-in versus split-sample reference.
    if s.get("plugin"):
        sh = [abs(r["shift_pct"]) for r in s["plugin"]]
        m.add("satPlugShiftLo", min(sh), "{:.1f}")
        m.add("satPlugShiftHi", max(sh), "{:.1f}")
        m.add("satPlugGrid",
              ",".join(str(r["n"]) for r in s["plugin"]), "{}")

    # Per-regime radii: the negative result.
    if s.get("by_regime"):
        by = {r["regime"]: r for r in s["by_regime"]}
        for key, tag in (("healthy", "Nom"), ("outer_race", "Outer"),
                         ("inner_race", "Inner"), ("ball_fault", "Ball")):
            if key in by:
                m.add(f"satRadius{tag}", by[key]["radius"], "{:.2f}")
        ratios = [r["ratio"] for r in s["by_regime"]]
        m.add("satRatioLo", min(ratios), "{:.2f}")
        m.add("satRatioHi", max(ratios), "{:.2f}")


def end_to_end(d, m):
    """
    The detection range is quoted in two places far apart in the paper: in the
    end-to-end results and again in the saturation discussion, where it carries
    the argument that a radius is not a detector. Those two had already drifted
    apart once, the second still citing a range from a superseded operator.
    Emitting one macro makes that particular divergence impossible.
    """
    e = d["end_to_end"]
    det = [r["detection"] for r in e.get("regimes", []) if "detection" in r]
    if det:
        m.add("etoeDetectLo", min(det), "{:.1f}")
        m.add("etoeDetectHi", max(det), "{:.1f}")
    m.add("etoeFAR", e["healthy_far"], "{:.2f}")



def nasa(d, m):
    """
    The IMS field numbers the prose quotes. These were hand-copied until the
    trajectory figure, generated from the pipeline, disagreed with the
    hand-written table by seven hours on one bearing.
    """
    import numpy as np
    from mssp_repro.field.residuals import describe_trajectory, load_cache

    path = Path(__file__).parent / "results" / "field_residuals_ims.npz"
    if not path.exists():
        raise KeyError("field_residuals_ims.npz absent")
    cache = load_cache(path)
    rows = [describe_trajectory(cache["scores"][i])
            for i in range(len(cache["meta"]["bearings"]))]

    lead = [r["lead_hours"] for r in rows]
    taus = [r["tau"] for r in rows]
    ns = [r["n"] for r in rows]
    exc = [100 * r["exceedance_post"] for r in rows]

    m.add("nasaBearings", len(rows), "{:d}")
    m.add("nasaRecordings", rows[0]["n_recordings"], "{:d}")
    m.add("nasaInactive", rows[0].get("n_trailing_inactive", 0), "{:d}")
    m.add("nasaLeadLo", min(lead), "{:.1f}")
    m.add("nasaLeadHi", max(lead), "{:.1f}")
    m.add("nasaLeadMean", float(np.mean(lead)), "{:.1f}")
    m.add("nasaNLo", min(ns), "{:d}")
    m.add("nasaNHi", max(ns), "{:d}")
    m.add("nasaTauLo", min(taus), "{:.2e}")
    m.add("nasaTauHi", max(taus), "{:.2e}")
    m.add("nasaTauSpread", max(taus) / min(taus), "{:.1f}")
    m.add("nasaExceedanceMean", float(np.mean(exc)), "{:.1f}")

SECTIONS = [("saturation", saturation), ("end_to_end", end_to_end),
            ("nasa", nasa)]


def main():
    if not DATA_PATH.exists():
        raise SystemExit(f"{DATA_PATH} not found; run `python3 run_all.py` first")
    d = json.loads(DATA_PATH.read_text())
    meta = d.get("_meta", {})
    if meta.get("quick"):
        print("WARNING: data.json came from a --quick run; the macros it "
              "produces are not quotable.")

    m, missing = Macros(), []
    for key, fn in SECTIONS:
        # The NASA section reads its own Layer B artefact rather than
        # data.json, so it decides for itself whether it can run.
        if key != "nasa" and key not in d:
            missing.append(key)
            continue
        try:
            fn(d, m)
        except (KeyError, IndexError) as exc:
            missing.append(f"{key} ({exc})")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(m.render(meta))
    print(f"  wrote {OUT.relative_to(HERE.parent)}  "
          f"({len(m._m)} macro(s))")
    if missing:
        # Deliberately not fatal here: the compile failure on the undefined
        # macro is the better error, because it names the sentence that needs
        # the number rather than the section that failed to produce it.
        print(f"  NOT emitted, section absent from data.json: "
              f"{', '.join(missing)}")
        print("  the document will fail to compile on the undefined macro, "
              "which is intended")
    if d.get("_carried_over"):
        c = d["_carried_over"]
        print(f"  NOTE: {len(c['keys'])} section(s) in data.json were carried "
              f"over from the run of {c['from_run']}; macros derived from "
              "them are that old")
    return 0


if __name__ == "__main__":
    sys.exit(main())
