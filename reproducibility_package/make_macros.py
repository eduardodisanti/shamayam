#!/usr/bin/env python3
"""
Emit `tables/values.tex`: the numbers the PROSE quotes, as LaTeX macros.

WHY THIS EXISTS
---------------
`make_tables.py` closed the gap between the code and the tables, and
`make_figures.py` closed it for the figures. The docstring of the former
admitted what remained open:

    The prose around the tables still quotes numbers inline, and that prose is
    NOT generated; it remains the one place where a value can go stale
    unnoticed.

That is not a hypothetical. A sentence reading "coverage falls to 0.9788"
survives a re-run that moves the value to 0.9805, and nothing in the build
complains, because LaTeX cannot tell a stale digit from a fresh one. The
failure is silent and it is in the argument, not in an appendix.

This script removes the last hand-copied numbers by emitting a `\\newcommand`
for each. The paper says `\\satBiasHi` where it used to say `6.43`, so a
regenerated run propagates into the sentence as well as into the table. If a
macro is undefined the document fails to compile, which is the desired
behaviour: an unavailable number should stop the build rather than silently
retain an old one.

    python3 make_macros.py          # -> tables/values.tex

SCOPE. Only quantities that (i) appear inline in the prose and (ii) are
produced by `run_all.py` are emitted. Quantities fixed by the design -- the
target level, the commissioning floor, the degenerate range -- are theory, not
measurement, and stay written out in the text where the reader can check them
against the propositions.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
DATA_PATH = HERE / "results" / "data.json"
OUT = HERE.parent / "tables" / "values.tex"

# Design constants of run_all.py that the derived macros below need. They are
# repeated here rather than imported because run_all imports TensorFlow.
E2E_N_CAL, E2E_N_EVAL, E2E_ALPHA = 120, 1500, 0.02   # experiment_end_to_end
DRIFT_N_COMMISSION = 120                            # experiment_drift


class Macros:
    """
    Collector that refuses to emit a macro twice under different values, and
    records the section each macro came from so an absent section produces an
    absent macro rather than a plausible-looking wrong one.
    """

    def __init__(self):
        self._m = {}

    def add(self, name, value, fmt="{:.2f}"):
        text = fmt.format(value) if not isinstance(value, str) else value
        if name in self._m and self._m[name] != text:
            raise ValueError(f"macro {name} redefined: "
                             f"{self._m[name]!r} -> {text!r}")
        self._m[name] = text
        return text

    def render(self, meta):
        lines = [
            "% GENERATED by experiments/make_macros.py -- do not edit.",
            f"% source: results/data.json, run {meta.get('generated_utc','?')}"
            f", seed {meta.get('seed','?')}"
            + ("  [QUICK RUN, not quotable]" if meta.get("quick") else ""),
            "% regenerate: python3 run_all.py && python3 make_macros.py",
            "% also read: results/field_residuals_ims.npz (nasa*), "
            "results/stability.json (stab*)",
            "%",
            "% Each macro below is a measured quantity quoted inline in the",
            "% prose. An undefined macro is a compile error by design.",
            "",
        ]
        for name in sorted(self._m):
            lines.append(f"\\newcommand{{\\{name}}}{{{self._m[name]}}}")
        return "\n".join(lines) + "\n"


def _row(rows, n):
    for r in rows:
        if r["n"] == n:
            return r
    raise KeyError(f"no row at n={n}")


def _sci(x, sig=3):
    """LaTeX scientific notation for use inside math: 2.62\\times10^{-3}.
    With one significant figure a unit mantissa is dropped: 10^{-3}."""
    mant, exp = f"{x:.{sig - 1}e}".split("e")
    exp = int(exp)
    if sig == 1 and mant == "1":
        return f"10^{{{exp}}}"
    return f"{mant}\\times10^{{{exp}}}"


def _num(x, sig=3):
    """Plain decimal between 0.1 and 1000 (38.6, 0.461), else _sci."""
    if 0.1 <= abs(x) < 1000:
        return f"{x:.{sig}g}"
    return _sci(x, sig)


def _pct(x):
    """A percentage to one decimal, without a trailing .0 (100, 91.5)."""
    t = f"{x:.1f}"
    return t[:-2] if t.endswith(".0") else t


_WORDS = ("zero", "one", "two", "three", "four", "five", "six", "seven",
          "eight", "nine", "ten", "eleven", "twelve")


def _word(k):
    return _WORDS[k] if 0 <= k < len(_WORDS) else str(k)


def training(d, m):
    """
    The A2 training run, quoted in the description of the operator. The
    sentence says training "terminated" by early stopping; a run that used its
    whole budget (as the TensorFlow 2.21 regeneration did) would make that
    sentence false while leaving every number plausible. So the epoch count
    and the best epoch are emitted ONLY for an early-stopped run, and any
    other run fails the build at that sentence, which then has to be
    rewritten rather than silently refilled.
    """
    t = d["training"]
    m.add("trainParams", f"{t['parameters']:,}".replace(",", "{,}"))
    m.add("trainEpochsBudget", t["epochs_budget"], "{:d}")
    if t.get("stop_reason") == "early_stopping":
        m.add("trainEpochsRun", t["epochs_run"], "{:d}")
        m.add("trainBestEpoch", t["best_epoch"], "{:d}")
    m.add("trainBestLoss", _sci(t["best_loss"], 3))
    m.add("trainLrInitial", _sci(t["initial_lr"], 1))
    m.add("trainLrFinal", _sci(t["final_lr"], 1))
    m.add("trainLrReductions", _word(t["lr_reductions"]))


def saturation(d, m):
    s = d["saturation"]
    rows = s["rows"]
    lo, hi = s["degenerate_range"]

    m.add("satRefWindows", s.get("reference_windows", 0), "{:d}")
    m.add("satEvalBlock", s.get("eval_block", 0), "{:d}")
    m.add("satReps", s.get("reps", 0), "{:d}")
    # R_p itself is deliberately NOT emitted: the generated caption of
    # Table~\ref{tab:saturation} already carries it, and a second copy in the
    # prose would be one more place for the two to disagree.

    # Bias inside the degenerate range, and the discontinuity at its exit.
    m.add("satBiasLo", _row(rows, lo)["bias_pct"], "{:.2f}")
    m.add("satBiasHi", _row(rows, hi)["bias_pct"], "{:.2f}")
    m.add("satBiasDrop", _row(rows, hi + 1)["bias_pct"], "{:.2f}")

    # Interpolated coverage at the ends of the grid.
    first, last = rows[0], rows[-1]
    m.add("satInterpFirstN", first["n"], "{:d}")
    m.add("satInterpFirstCov", first["interpolated_coverage"], "{:.3f}")
    m.add("satInterpLastN", last["n"], "{:d}")
    m.add("satInterpLastCov", last["interpolated_coverage"], "{:.3f}")

    # Agreement with the exact coverage, which is the sharper claim than the
    # inequality and therefore the one the prose should make.
    if "max_abs_z" in s:
        m.add("satMaxZ", s["max_abs_z"], "{:.1f}")
    cert = [r for r in rows if r.get("coverage_theory") is not None]
    if cert:
        m.add("satExactAtDegHi",
              _row(cert, hi)["coverage_theory"], "{:.4f}")
        m.add("satCovAtDegHi", _row(cert, hi)["coverage"], "{:.4f}")

    # Plug-in versus split-sample reference.
    if s.get("plugin"):
        sh = [abs(r["shift_pct"]) for r in s["plugin"]]
        m.add("satPlugShiftLo", min(sh), "{:.1f}")
        m.add("satPlugShiftHi", max(sh), "{:.1f}")
        m.add("satPlugGrid",
              ",".join(str(r["n"]) for r in s["plugin"]), "{}")

    # Per-regime radii: the negative result.
    if s.get("by_regime"):
        by = {r["regime"]: r for r in s["by_regime"]}
        for key, tag in (("healthy", "Nom"), ("outer_race", "Outer"),
                         ("inner_race", "Inner"), ("ball_fault", "Ball")):
            if key in by:
                m.add(f"satRadius{tag}", by[key]["radius"], "{:.2f}")
        ratios = [r["ratio"] for r in s["by_regime"]]
        m.add("satRatioLo", min(ratios), "{:.2f}")
        m.add("satRatioHi", max(ratios), "{:.2f}")


def end_to_end(d, m):
    """
    The detection range is quoted in two places far apart in the paper: in the
    end-to-end results and again in the saturation discussion, where it carries
    the argument that a radius is not a detector. Those two had already drifted
    apart once, the second still citing a range from a superseded operator.
    Emitting one macro makes that particular divergence impossible.
    """
    e = d["end_to_end"]
    det = [r["detection"] for r in e.get("regimes", []) if "detection" in r]
    if det:
        m.add("etoeDetectLo", min(det), "{:.1f}")
        m.add("etoeDetectHi", max(det), "{:.1f}")
    m.add("etoeFAR", e["healthy_far"], "{:.2f}")

    # Median residuals and per-regime detection, quoted in one sentence.
    m.add("etoeMedNom", _sci(e["healthy_median_residual"], 3))
    tags = {"outer_race": "Outer", "inner_race": "Inner", "ball_fault": "Ball"}
    for r in e.get("regimes", []):
        tag = tags[r["regime"]]
        m.add(f"etoeMed{tag}", _sci(r["median_residual"], 3))
        m.add(f"etoeDetect{tag}", _pct(r["detection"]))

    # Simulated assets sharing one operator: radii and their spread.
    names = ("One", "Two", "Three", "Four")
    radii = e["asset_radii"]
    if len(radii) != len(names):
        raise KeyError(f"expected {len(names)} asset radii, got {len(radii)}")
    for tag, r in zip(names, radii):
        m.add(f"etoeAssetRadius{tag}", _sci(r, 3))
    m.add("etoeAssetSpread", e["spread"], "{:.2f}")

    # How unusual the observed held-out rate is under the guarantee itself.
    # A single calibration attains a RANDOM coverage C ~ Beta(k, n+1-k); the
    # held-out count of exceedances is then beta-binomial. The constants are
    # those of run_all.experiment_end_to_end (120 commissioning windows, 1500
    # held-out windows, alpha 0.02).
    import math
    from scipy.stats import betabinom
    n, n_eval, alpha = E2E_N_CAL, E2E_N_EVAL, E2E_ALPHA
    k = math.ceil((1 - alpha) * (n + 1))
    count = round(e["healthy_far"] * n_eval / 100)
    m.add("etoeFARMean", 100 * (n + 1 - k) / (n + 1), "{:.2f}")
    m.add("etoeFARPExceed",
          100 * betabinom(n_eval, n + 1 - k, k).sf(count - 1), "{:.0f}")



def nasa(d, m):
    """
    The IMS field numbers the prose quotes. These were hand-copied until the
    trajectory figure, generated from the pipeline, disagreed with the
    hand-written table by seven hours on one bearing.
    """
    import numpy as np
    from mssp_repro.field.residuals import describe_trajectory, load_cache

    path = Path(__file__).parent / "results" / "field_residuals_ims.npz"
    if not path.exists():
        raise KeyError("field_residuals_ims.npz absent")
    cache = load_cache(path)
    rows = [describe_trajectory(cache["scores"][i])
            for i in range(len(cache["meta"]["bearings"]))]

    lead = [r["lead_hours"] for r in rows]
    taus = [r["tau"] for r in rows]
    ns = [r["n"] for r in rows]
    exc = [100 * r["exceedance_post"] for r in rows]

    m.add("nasaBearings", len(rows), "{:d}")
    m.add("nasaRecordings", rows[0]["n_recordings"], "{:d}")
    m.add("nasaInactive", rows[0].get("n_trailing_inactive", 0), "{:d}")
    m.add("nasaLeadLo", min(lead), "{:.1f}")
    m.add("nasaLeadHi", max(lead), "{:.1f}")
    m.add("nasaLeadMean", float(np.mean(lead)), "{:.1f}")
    m.add("nasaNLo", min(ns), "{:d}")
    m.add("nasaNHi", max(ns), "{:d}")
    m.add("nasaTauLo", min(taus), "{:.2e}")
    m.add("nasaTauHi", max(taus), "{:.2e}")
    m.add("nasaTauSpread", max(taus) / min(taus), "{:.1f}")
    m.add("nasaExceedanceMean", float(np.mean(exc)), "{:.1f}")

def drift(d, m):
    """
    The attractor-drift experiment on the simulator. Departure index, delay,
    severity at detection and post-departure exceedance per fault family, and
    the false-alarm rate on the nominal records between commissioning and
    onset, which the prose discusses at length and which therefore must not be
    a copied number.
    """
    regs = {r["regime"]: r for r in d["drift"]["regimes"]}
    tags = {"inner_race": "Inner", "outer_race": "Outer", "ball_fault": "Ball"}
    onsets = {r["onset"] for r in regs.values()}
    if len(onsets) != 1:
        raise KeyError(f"onset differs across regimes: {onsets}")
    onset = onsets.pop()
    m.add("driftOnset", onset, "{:d}")
    m.add("driftPreN", onset - DRIFT_N_COMMISSION, "{:d}")
    m.add("driftPreStep", 100 / (onset - DRIFT_N_COMMISSION), "{:.1f}")
    pre = {r["far_pre"] for r in regs.values()}
    if len(pre) != 1:
        raise KeyError(f"pre-onset FAR differs across regimes: {pre}")
    m.add("driftFARPre", 100 * pre.pop(), "{:.1f}")
    for key, tag in tags.items():
        r = regs[key]
        if r["detected"] is None:
            continue
        m.add(f"driftDetect{tag}", r["detected"], "{:d}")
        m.add(f"driftDelay{tag}", r["delay"], "{:d}")
        m.add(f"driftSev{tag}", r["severity_at_detection"], "{:.3f}")
        m.add(f"driftExc{tag}", 100 * r["exceedance_post"], "{:.1f}")


def adequacy(d, m):
    """
    The distance-proxy probe. Only quantities with a physical reading are
    emitted: the distance each operator accepts, relative to the nominal
    spacing, and the residual of the convolutional operator across the probe.
    The residual of the linear operator is numerically zero everywhere
    (1e-31 to 1e-27); ratios of it are rounding, not measurement, so the only
    thing emitted about it is its order of magnitude.
    """
    import math
    ops = d["adequacy"]["operators"]
    pca = next(o for o in ops if o["operator"].startswith("PCA"))
    conv = next(o for o in ops if o["operator"].startswith("Conv"))
    m.add("adqPCAMaxDist", pca["max_accepted_distance"], "{:.0f}")
    m.add("adqPCARatio", pca["ratio"], "{:.0f}")
    top = max(r["residual"] for r in pca["rows"])
    m.add("adqPCAResOrder", f"10^{{{math.floor(math.log10(top))}}}")
    m.add("adqConvRatio", conv["ratio"], "{:.1f}")
    m.add("adqRatioBetween", pca["ratio"] / conv["ratio"], "{:.0f}")
    m.add("adqConvResLo", _num(conv["rows"][0]["residual"], 3))
    m.add("adqConvResHi", _num(conv["rows"][-1]["residual"], 3))
    m.add("adqConvGrowthOrders",
          _word(math.floor(math.log10(conv["residual_growth"]))))
    m.add("adqPCABallDR", pca["detection"]["ball_fault"], "{:.0f}")
    m.add("adqConvBallDR", conv["detection"]["ball_fault"], "{:.0f}")


def stability(d, m):
    """
    The seed study of the field pipeline. The prose around
    Table~\\ref{tab:stability} quotes ranges over its columns, and one of them
    (how many bearing--seed pairs commission at the floor) had drifted from
    the table it summarises. Every quantity below is computed exactly as
    `make_tables.table_stability` computes the column it summarises.
    """
    import numpy as np
    from make_tables import ESTIMATOR_ONLY_SPREAD

    path = Path(__file__).parent / "results" / "stability.json"
    if not path.exists():
        raise KeyError("stability.json absent")
    s = json.loads(path.read_text())
    rows = s["rows"]
    est = s.get("estimator_only", ESTIMATOR_ONLY_SPREAD)
    bearings = rows[0]["bearings"]

    def col(i, key):
        return np.array([r["field"][i][key] for r in rows], dtype=float)

    def rel(x):
        return 100 * x.std(ddof=1) / x.mean()

    spread = [rel(col(i, "tau")) for i in range(len(bearings))]
    norm = [rel(col(i, "tau_normalised")) for i in range(len(bearings))]
    est_pct = [100 * e for e in est]
    share = [e / sp * 100 for e, sp in zip(est_pct, spread)]
    factor = [sp / nr for sp, nr in zip(spread, norm)]

    m.add("stabSpreadLo", min(spread), "{:.1f}")
    m.add("stabSpreadHi", max(spread), "{:.1f}")
    m.add("stabEstLo", min(est_pct), "{:.1f}")
    m.add("stabEstHi", max(est_pct), "{:.1f}")
    m.add("stabEstShareLo", min(share), "{:.0f}")
    m.add("stabEstShareHi", max(share), "{:.0f}")
    m.add("stabNormSpreadLo", min(norm), "{:.1f}")
    m.add("stabNormSpreadHi", max(norm), "{:.1f}")
    m.add("stabNormFactorLo", min(factor), "{:.1f}")
    m.add("stabNormFactorHi", max(factor), "{:.1f}")

    # Commissioning at the floor: how many of the bearing--seed pairs.
    ns = [f["n"] for r in rows for f in r["field"]]
    floor = min(ns)
    m.add("stabFloorN", floor, "{:d}")
    m.add("stabFloorCount", sum(n == floor for n in ns), "{:d}")
    m.add("stabPairs", len(ns), "{:d}")

    # Bearing 1: lead time across seeds, and the radius spread behind it.
    i1 = bearings.index(1)
    lead = col(i1, "lead_hours")
    m.add("stabBOneLeadLo", lead.min(), "{:.1f}")
    m.add("stabBOneLeadHi", lead.max(), "{:.1f}")
    m.add("stabBOneLeadSpread", rel(lead), "{:.2f}")
    m.add("stabBOneTauSpread", spread[i1], "{:.1f}")

    # The sparsity check. "All units active under every seed" is a claim, so
    # the count is emitted only when it holds.
    units = len(rows[0]["latent_sd"])
    if all(r["active@0.01"] == units for r in rows):
        m.add("stabLatentActive", units, "{:d}")
    pr = np.array([r["participation_ratio"] for r in rows])
    tm = np.array([r["tau_mc"] for r in rows])
    m.add("stabPRCorrTauMC", float(np.corrcoef(pr, tm)[0, 1]), "{:+.2f}")
    # The magnitude a correlation over this many seeds must exceed to be
    # distinguishable from zero at the 5% level (two-sided).
    from scipy.stats import t as student_t
    q = student_t.ppf(0.975, len(rows) - 2)
    m.add("stabCorrCrit", q / np.sqrt(len(rows) - 2 + q * q), "{:.2f}")

    # Range of the departure index across seeds, per bearing.
    for i, tag in enumerate(("One", "Two", "Three", "Four")[:len(bearings)]):
        dep = col(i, "departure")
        m.add(f"stabDepRange{tag}", int(dep.max() - dep.min()), "{:d}")


SECTIONS = [("training", training), ("saturation", saturation),
            ("end_to_end", end_to_end), ("drift", drift),
            ("adequacy", adequacy), ("nasa", nasa),
            ("stability", stability)]

# Sections that read their own artefact rather than data.json.
OWN_ARTEFACT = ("nasa", "stability")


def build(data_path=DATA_PATH):
    """
    Compute every macro and return (text, macros, missing, data). Separate
    from `main` so a test can regenerate `values.tex` in memory and compare it
    byte for byte with the committed file.
    """
    d = json.loads(Path(data_path).read_text())
    meta = d.get("_meta", {})
    m, missing = Macros(), []
    for key, fn in SECTIONS:
        if key not in OWN_ARTEFACT and key not in d:
            missing.append(key)
            continue
        try:
            fn(d, m)
        except (KeyError, IndexError) as exc:
            missing.append(f"{key} ({exc})")
    return m.render(meta), m, missing, d


def main():
    if not DATA_PATH.exists():
        raise SystemExit(f"{DATA_PATH} not found; run `python3 run_all.py` first")
    text, m, missing, d = build()
    if d.get("_meta", {}).get("quick"):
        print("WARNING: data.json came from a --quick run; the macros it "
              "produces are not quotable.")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text)
    print(f"  wrote {OUT.relative_to(HERE.parent)}  "
          f"({len(m._m)} macro(s))")
    if missing:
        # Deliberately not fatal here: the compile failure on the undefined
        # macro is the better error, because it names the sentence that needs
        # the number rather than the section that failed to produce it.
        print(f"  NOT emitted, section absent from data.json: "
              f"{', '.join(missing)}")
        print("  the document will fail to compile on the undefined macro, "
              "which is intended")
    if d.get("_carried_over"):
        c = d["_carried_over"]
        print(f"  NOTE: {len(c['keys'])} section(s) in data.json were carried "
              f"over from the run of {c['from_run']}; macros derived from "
              "them are that old")
    return 0


if __name__ == "__main__":
    sys.exit(main())
