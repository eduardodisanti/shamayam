def experiment_exchangeability(out, n_trials, n_perm):
    w = out.write
    w("\n\nEXPERIMENT 4 -- permutation test for the exchangeability assumption [ass:exchangeability]\n")
    w("=" * 74 + "\n")
    se = np.sqrt(0.05 * 0.95 / n_trials)
    w("Rejection rate at level 0.05. Under exchangeability this is the size\n"
      "and must not exceed 0.05; under injected drift it is the power.\n")
    w(f"Binomial standard error of the size column at {n_trials} trials is "
      f"{se:.4f},\nso deviations up to about {3*se:.3f} are sampling noise. "
      "The statistic is rank-\nbased, hence its size is distribution-free: any "
      "systematic spread across\nrows would indicate an implementation fault, "
      "not a property of the test.\n\n")
    w(f"  {'distribution':22s}{'size':>8s}" +
      "".join(f"{'drift '+str(s):>12s}" for s in (0.5, 1.0, 2.0, 3.0)) + "\n")

    for name, gen in make_distributions(np.random.default_rng(SEED + 3)).items():
        cells = []
        for slope in (0.0, 0.5, 1.0, 2.0, 3.0):
            hits = 0
            for t in range(n_trials):
                s = gen(60)
                if slope > 0:
                    s = inject_drift(s, slope=slope)
                r = permutation_exchangeability_test(
                    s, n_permutations=n_perm, random_state=t)
                hits += int(r["p_value"] < 0.05)
            cells.append(hits / n_trials)
        DATA.setdefault("exchangeability", {}).setdefault("rows", []).append(
            {"distribution": name, "size": float(cells[0]),
             "power": {str(s): float(c)
                       for s, c in zip((0.5, 1.0, 2.0, 3.0), cells[1:])}})
        w(f"  {name:22s}{cells[0]:8.3f}" +
          "".join(f"{c:12.3f}" for c in cells[1:]) + "\n")
    w("\n  A drifting commissioning window voids the exchangeability assumption [ass:exchangeability]; the test must\n"
      "  detect it. Size at or below nominal, power rising with drift.\n")


