def experiment_selection(out, n_trials, n_eval):
    rng = np.random.default_rng(SEED + 1)
    dists = make_distributions(rng)
    w = out.write
    w("\n\nEXPERIMENT 2 -- stopping selection isolated from sample size\n")
    w("=" * 74 + "\n")
    w("Adaptive stopping at n*, versus a fixed-n calibration on an\n"
      "INDEPENDENT block of the same size n*. The A2-vs-A4 contrast of\n"
      "Experiment 1 conflates these; this separates them.\n\n")
    w(f"  {'distribution':22s}{'med n*':>8s}{'adaptive':>11s}"
      f"{'fixed@n*':>11s}{'selection':>11s}\n")

    rows = []
    for name, gen in dists.items():
        ca, cf, ns = [], [], []
        for _ in range(n_trials):
            pool = gen(MAX_CALIBRATION_SIZE + n_eval)
            cal, ev = pool[:MAX_CALIBRATION_SIZE], pool[MAX_CALIBRATION_SIZE:]
            trace = AdaptiveOperationalRadius(
                certified_order_statistic, window_size=MAX_CALIBRATION_SIZE,
                min_samples=MIN_WARMUP_SAMPLES).warmup_trace(cal)
            idx = find_convergence_index(
                trace, lookback=CONVERGENCE_LOOKBACK,
                tolerance=CONVERGENCE_TOLERANCE,
                consecutive=CONVERGENCE_CONSECUTIVE,
                min_index=MIN_CALIBRATION_SIZE - 1)
            if idx is None:
                continue
            n_star = idx + 1
            tau_ad = trace[idx]
            tau_fx = certified_order_statistic(gen(n_star), ALPHA)
            if not (np.isfinite(tau_ad) and np.isfinite(tau_fx)):
                continue
            ca.append(np.mean(ev <= tau_ad))
            cf.append(np.mean(ev <= tau_fx))
            ns.append(n_star)
        a, f = float(np.mean(ca)), float(np.mean(cf))
        rows.append((name, np.median(ns), a, f))
        w(f"  {name:22s}{np.median(ns):8.0f}{a:11.5f}{f:11.5f}"
          f"{100*(a-f):+11.2f}\n")
    w("\n  'selection' = coverage(adaptive) - coverage(fixed at same n), pp.\n")
    w("  Negative would mean stopping biases tau downward.\n")
    return rows


