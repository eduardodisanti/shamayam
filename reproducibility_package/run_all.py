def _run_arm(cal, ev, *, estimator, adaptive):
    if adaptive:
        trace = AdaptiveOperationalRadius(
            estimator, window_size=MAX_CALIBRATION_SIZE,
            min_samples=MIN_WARMUP_SAMPLES,
        ).warmup_trace(cal)
        idx = find_convergence_index(
            trace, lookback=CONVERGENCE_LOOKBACK,
            tolerance=CONVERGENCE_TOLERANCE,
            consecutive=CONVERGENCE_CONSECUTIVE,
            min_index=MIN_CALIBRATION_SIZE - 1,
        )
        if idx is None:
            return np.nan, np.nan, np.nan
        tau, n_used = trace[idx], idx + 1
    else:
        n_used = 50
        tau = estimator(cal[:n_used])

    if not np.isfinite(tau):
        return np.nan, n_used, np.nan
    return tau, n_used, float(np.mean(ev <= tau))


ARMS = [
    ("A1", "interpolated", "adaptive", interpolated_quantile, True),
    ("A2", "certified", "adaptive", certified_order_statistic, True),
    ("A3", "interpolated", "fixed n=50", interpolated_quantile, False),
    ("A4", "certified", "fixed n=50", certified_order_statistic, False),
]


def experiment_arms(out, n_trials, n_eval):
    rng = np.random.default_rng(SEED)
    dists = make_distributions(rng)

    n_fix = 50
    k_fix = k_alpha(n_fix, ALPHA)
    lo, hi = coverage_band(n_fix, ALPHA)

    w = out.write
    w("EXPERIMENT 1 -- arm design: estimator x stopping rule\n")
    w("=" * 74 + "\n")
    w(f"alpha={ALPHA:.3f}  target coverage={1-ALPHA:.3f}  "
      f"trials={n_trials}  eval={n_eval}\n")
    w(f"coverage proposition at fixed n={n_fix}: k_alpha={k_fix}, "
      f"exact coverage={exact_coverage(n_fix, ALPHA):.5f}, "
      f"band=[{lo:.5f},{hi:.5f}]\n")
    w(f"commissioning floor   : n >= {minimum_commissioning_length(ALPHA)}\n")
    w(f"degenerate band       : n in {degenerate_range(ALPHA)}\n")
    w(f"stopping-rule floor   : {stopping_rule_floor()} "
      "(combinatorial, independent of alpha)\n\n")

    w(f"{'residual distribution':22s}" + "".join(f"{a[0]:>9s}" for a in ARMS)
      + f"{'med n A1':>10s}\n")
    w("-" * 74 + "\n")

    pooled = {a[0]: [] for a in ARMS}
    for name, gen in dists.items():
        far, med_n = {}, np.nan
        for tag, _, _, estimator, adaptive in ARMS:
            covs, ns = [], []
            for _ in range(n_trials):
                pool = gen(MAX_CALIBRATION_SIZE + n_eval)
                _, n_u, cov = _run_arm(
                    pool[:MAX_CALIBRATION_SIZE], pool[MAX_CALIBRATION_SIZE:],
                    estimator=estimator, adaptive=adaptive)
                if np.isfinite(cov):
                    covs.append(cov)
                    ns.append(n_u)
            far[tag] = 100.0 * (1.0 - np.mean(covs))
            pooled[tag].append(np.mean(covs))
            if tag == "A1":
                med_n = np.median(ns)
        DATA.setdefault("arms", {}).setdefault("by_distribution", []).append(
            {"distribution": name,
             "far": {tag: float(far[tag]) for tag, *_ in ARMS},
             "median_n_A1": float(med_n)})
        w(f"{name:22s}" + "".join(f"{far[a[0]]:9.2f}" for a in ARMS)
          + f"{med_n:10.0f}\n")

    w("-" * 74 + "\n")
    w(f"entries are out-of-sample false-alarm rate (%), nominal "
      f"{100*ALPHA:.1f}%\n\n")

    c = {t: float(np.mean(v)) for t, v in pooled.items()}
    # sd of the per-trial coverage of an order statistic is that of a Beta
    # variate; report the pooled Monte Carlo standard error explicitly so the
    # trial count can be judged rather than assumed adequate.
    n_pool = n_trials * len(dists)
    se = {t: float(np.std(v, ddof=1) / np.sqrt(len(v))) if len(v) > 1 else float("nan")
          for t, v in pooled.items()}
    w(f"pooled across distributions ({n_pool} trials per arm; "
      "'se' is the standard error across distribution means)\n")
    for tag, est, stop, _, _ in ARMS:
        w(f"  {tag}  {est:12s} {stop:10s}  coverage {c[tag]:.5f} "
          f"(se {se[tag]:.5f})  FAR {100*(1-c[tag]):5.2f}%  "
          f"excess {100*(1-c[tag])-100*ALPHA:+5.2f} pp\n")
    w(f"\n  theory predicts arm A4 coverage = {exact_coverage(n_fix, ALPHA):.5f}; "
      f"observed {c['A4']:.5f}, "
      f"deviation {abs(c['A4']-exact_coverage(n_fix, ALPHA))/max(se['A4'],1e-12):.1f} se.\n")

    w("\nbias decomposition (coverage loss, percentage points)\n")
    w(f"  interpolation, fixed n        : {100*(c['A4']-c['A3']):+5.2f}"
      "   <- interpolation bias\n")
    w(f"  interpolation, adaptive       : {100*(c['A2']-c['A1']):+5.2f}\n")
    w(f"  adaptive stopping, certified  : {100*(c['A4']-c['A2']):+5.2f}"
      "   <- stopping effect; the sign is the correction\n")
    w(f"  adaptive stopping, interp.    : {100*(c['A3']-c['A1']):+5.2f}\n")
    DATA.setdefault("arms", {}).update({
        "alpha": float(ALPHA), "n_fixed": int(n_fix), "k_alpha": int(k_fix),
        "predicted_coverage": float(exact_coverage(n_fix, ALPHA)),
        "pooled_coverage": {k: float(v) for k, v in c.items()},
        "pooled_se": {k: float(v) for k, v in se.items()},
        "trials_per_arm": int(n_pool),
        "bias_interpolation_fixed": float(100*(c['A4']-c['A3'])),
        "bias_interpolation_adaptive": float(100*(c['A2']-c['A1'])),
        "bias_stopping_certified": float(100*(c['A4']-c['A2'])),
        "bias_stopping_interpolated": float(100*(c['A3']-c['A1'])),
        "commissioning_floor": int(minimum_commissioning_length(ALPHA)),
        "degenerate_range": [int(x) for x in degenerate_range(ALPHA)],
        "stopping_rule_floor": int(stopping_rule_floor())})
    return c


