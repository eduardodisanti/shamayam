def experiment_dimension(out, n_points):
    """
    The embedding reading predicts one direction per nuisance parameter that
    acts non-trivially. That is falsifiable, and it is tested here by varying
    how many parameters are active and checking whether the estimate follows.

    Absolute accuracy is not the criterion: the maximum-likelihood estimator
    is known to be biased downward, increasingly so with dimension. Tracking
    is the criterion, because a wrong reading would not track.
    """
    w = out.write
    w("\n\nEXPERIMENT 7 -- intrinsic dimension of the nominal cloud\n")
    w("=" * 74 + "\n")
    w("Windows are delay-coordinate vectors of ambient dimension 1200. The\n"
      "embedding reading predicts one direction per active nuisance\n"
      "parameter; additive noise adds thickness, not dimension.\n\n")

    cfgs = [
        (dict(vary_amplitude=True,  vary_phase=False, vary_speed=False,
              vary_offset=False), "amplitude"),
        (dict(vary_amplitude=True,  vary_phase=True,  vary_speed=False,
              vary_offset=False), "amplitude+phase"),
        (dict(vary_amplitude=True,  vary_phase=True,  vary_speed=True,
              vary_offset=False), "amplitude+phase+speed"),
        (dict(vary_amplitude=True,  vary_phase=True,  vary_speed=True,
              vary_offset=True),  "all four"),
        (dict(vary_amplitude=False, vary_phase=True,  vary_speed=True,
              vary_offset=True),  "phase+speed+offset"),
        (dict(vary_amplitude=False, vary_phase=False, vary_speed=True,
              vary_offset=True),  "speed+offset"),
    ]
    w(f"  noise-free family, {n_points} points\n")
    w(f"  {'active nuisance parameters':30s}{'predicted':>10s}"
      f"{'k=10':>8s}{'k=20':>8s}{'k=40':>8s}{'gap@20':>9s}\n")
    for kw, name in cfgs:
        X = nominal_family(n_points, seed=SEED, **kw)
        e = levina_bickel(X, k_values=(10, 20, 40))
        pred = predicted_dimension(**kw)
        DATA.setdefault("dimension", {}).setdefault("tracking", []).append(
            {"parameters": name, "predicted": int(pred),
             "k10": float(e[10]), "k20": float(e[20]), "k40": float(e[40]),
             "gap_at_k20": float(e[20] - pred)})
        w(f"  {name:30s}{pred:10d}{e[10]:8.2f}{e[20]:8.2f}{e[40]:8.2f}"
          f"{e[20]-pred:+9.2f}\n")
    w("\n  Each additional parameter raises the estimate by close to one, and\n"
      "  the single-parameter case is recovered exactly. The residual gap\n"
      "  grows with dimension and is the known negative bias of the\n"
      "  estimator, not an unexplained discrepancy.\n")

    # ---- scale dependence under noise --------------------------------
    sim = BearingSignalSimulator(CWRU_PARAMS)
    X_noisy = _sim_windows(sim, "healthy", n_points, seed=SEED + 21)
    X_clean = nominal_family(n_points, seed=SEED)
    ks = (5, 10, 20, 40, 80, 160)
    e_n = levina_bickel(X_noisy, k_values=ks)
    e_c = levina_bickel(X_clean, k_values=ks)
    w("\n  scale dependence: the same estimator on the full simulator\n")
    w(f"  {'k':>6s}{'noise-free':>13s}{'with noise':>13s}\n")
    DATA.setdefault("dimension", {})["scale"] = [
        {"k": int(k), "noise_free": float(e_c[k]), "with_noise": float(e_n[k])}
        for k in ks]
    DATA["dimension"]["ambient"] = 1200
    for k in ks:
        w(f"  {k:6d}{e_c[k]:13.2f}{e_n[k]:13.2f}\n")
    w("\n  Below the noise level the cloud looks high-dimensional; as the\n"
      "  neighbourhood grows the manifold structure emerges and the estimate\n"
      "  approaches the noise-free value. Ambient dimension is 1200 and the\n"
      "  representation elsewhere retains 16 components, comfortably above\n"
      "  the intrinsic dimension in either regime.\n")


