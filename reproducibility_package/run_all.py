# Experiment 9 (A2) -- operator adequacy: the distance-proxy probe
# [ass:residual_proxy], [rem:level_not_shape]
# =====================================================================

def experiment_operator_adequacy(out, conv, epochs, n_fit=900):
    """
    Coverage holds for any residual; tightness does not. This experiment
    measures the difference between two operators calibrated identically.

    The linear operator is retained deliberately as a negative control. It
    detects the simulated faults perfectly well, and still fails the probe by
    two orders of magnitude, which is the point: good detection on the faults
    one happens to have is not evidence that the accepted region is tight.
    """
    from mssp_repro.conv_autoencoder import EXPECTED_PARAMS

    w = out.write
    w("\n\nEXPERIMENT 9 -- operator adequacy under the distance-proxy probe\n")
    w("=" * 74 + "\n")
    w("Latent codes are pushed away from the nominal range, decoded, and the\n"
      "residual is compared against the true distance to a disjoint nominal\n"
      "cloud. A residual that tracks distance rises; one that measures\n"
      "distance to a larger structure containing the nominal set stays flat.\n\n")

    sim = BearingSignalSimulator(CWRU_PARAMS)
    X_fit = _sim_windows(sim, "healthy", n_fit, seed=SEED + 41)
    X_cal = _sim_windows(sim, "healthy", 300, seed=SEED + 42)
    X_ev = _sim_windows(sim, "healthy", 600, seed=SEED + 43)
    X_ref = _sim_windows(sim, "healthy", 400, seed=SEED + 44)
    X_fault = {r: _sim_windows(sim, r, 300, seed=SEED + 45)
               for r in ("outer_race", "inner_race", "ball_fault")}

    class _PCAWithCodec(PCAResidualOperator):
        def encode(self, X):
            return self._pca.transform(np.asarray(X, dtype=np.float64))

        def decode(self, Z):
            return self._pca.inverse_transform(np.asarray(Z, dtype=np.float64))

    w(f"  Conv1D operator: {conv.n_parameters:,} trainable parameters "
      f"(technical note reports {EXPECTED_PARAMS:,}), {epochs} epochs,\n"
      "  op determinism enabled.\n")

    for name, op in (("PCA-16 (negative control)", _PCAWithCodec(16).fit(X_fit)),
                     ("Conv1D AE (technical note)", conv)):
        tau = certified_order_statistic(op.residual(X_cal), ALPHA)
        far = 100.0 * float(np.mean(op.residual(X_ev) > tau))
        dr = {k: 100.0 * float(np.mean(op.residual(v) > tau))
              for k, v in X_fault.items()}
        res = distance_proxy_probe(op, X_fit[:400], tau, reference=X_ref)

        w(f"\n  {name}\n")
        w(f"    tau={tau:.5g}   healthy FAR={far:.1f}%   "
          + "  ".join(f"{k.split('_')[0]} DR={v:.0f}%" for k, v in dr.items())
          + "\n")
        w(f"    {'shift (sd)':>11s}{'residual':>13s}{'distance':>11s}"
          f"{'accepted':>10s}\n")
        for row in res["rows"]:
            w(f"    {row['shift_sd']:11.0f}{row['residual']:13.3g}"
              f"{row['distance']:11.3g}"
              f"{('YES' if row['accepted'] else 'no'):>10s}\n")
        ratio = res["max_accepted_distance"] / max(res["nominal_scale"], 1e-12)
        w(f"    nominal spacing={res['nominal_scale']:.3g}   "
          f"max accepted distance={res['max_accepted_distance']:.3g}   "
          f"ratio={ratio:.1f}x\n")
        DATA.setdefault("adequacy", {}).setdefault("operators", []).append(
            {"operator": name, "tau": float(tau), "healthy_far": float(far),
             "detection": {k: float(v) for k, v in dr.items()},
             "nominal_scale": float(res["nominal_scale"]),
             "max_accepted_distance": float(res["max_accepted_distance"]),
             "ratio": float(ratio),
             "residual_growth": float(res["residual_growth"]),
             "passes": bool(passes_distance_proxy(res)),
             "rows": res["rows"]})
        w(f"    ADEQUACY: {'PASS' if passes_distance_proxy(res) else 'FAIL'}\n")

    w("\n  The linear control accepts points hundreds of times the nominal\n"
      "  spacing with residuals of order 1e-30: its accepted region is a slab\n"
      "  around the retained subspace, not a tube around the nominal manifold.\n"
      "  The convolutional operator accepts only at the nominal scale. Both\n"
      "  attain the calibrated coverage, which is precisely why coverage\n"
      "  cannot be used to choose between them.\n")


