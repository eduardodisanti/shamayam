def experiment_drift(out, op, n_rec=700, alpha=ALPHA):
    """
    The second dynamical reading: degradation is slow motion of the
    reconstructed orbit, not motion along a fixed one. The radius is
    commissioned on the early-life segment and then frozen, so an alarm means
    the region moved rather than the point within it.

    Self-contained analogue of a run-to-failure record; no archive required.
    """
    w = out.write
    w("\n\nEXPERIMENT 8 -- attractor drift under slow parameter change\n")
    w("=" * 74 + "\n")
    w(f"Chronological records of {n_rec} windows, the first half nominal.\n"
      "Severity then ramps smoothly. The radius is frozen after\n"
      "commissioning and never adapted, so a persistent departure indicates\n"
      "that the orbit has moved away from the commissioned neighbourhood.\n\n")

    sim = BearingSignalSimulator(CWRU_PARAMS)

    n_commission = 120                       # above the degenerate range
    w(f"  {'regime':13s}{'tau':>11s}{'onset':>7s}{'detected':>9s}"
      f"{'delay':>7s}{'sev@det':>9s}{'FAR pre':>9s}{'exceed post':>12s}\n")
    for regime in ("outer_race", "inner_race", "ball_fault"):
        X, sev = degradation_trajectory(n_rec, regime=regime, seed=SEED + 32,
                                        healthy_fraction=0.50)
        r = op.residual(X)
        tau = certified_order_statistic(r[:n_commission], alpha)
        flags = r > tau
        onset = int(np.argmax(sev > 0))
        det = first_persistent_departure(flags, q=8, p=10,
                                         start=n_commission)
        far_pre = (float(np.mean(flags[n_commission:onset]))
                   if onset > n_commission else float("nan"))
        exceed_post = float(np.mean(flags[det:])) if det is not None else float("nan")
        det_s = str(det) if det is not None else "none"
        delay_s = f"{det-onset:.0f}" if det is not None else "--"
        sev_s = f"{sev[det]:.3f}" if det is not None else "--"
        DATA.setdefault("drift", {}).setdefault("regimes", []).append(
            {"regime": regime, "tau": float(tau), "onset": int(onset),
             "detected": (int(det) if det is not None else None),
             "delay": (int(det - onset) if det is not None else None),
             "severity_at_detection": (float(sev[det]) if det is not None
                                       else None),
             "far_pre": float(far_pre), "exceedance_post": float(exceed_post),
             "residual": [float(v) for v in r],
             "severity": [float(v) for v in sev]})
        w(f"  {regime:13s}{tau:11.6f}{onset:7d}{det_s:>9s}{delay_s:>7s}"
          f"{sev_s:>9s}{100*far_pre:8.1f}%{100*exceed_post:11.1f}%\n")

    w("\n  'onset' is the first record with non-zero severity, 'detected' the\n"
      "  first persistent departure, and 'delay' the gap between them, all in\n"
      "  record index. 'sev@det' is the severity actually reached at\n"
      "  detection, so a small value means the departure was caught early in\n"
      "  the ramp. 'FAR pre' is measured on post-commissioning records before\n"
      "  onset, where the process is still nominal, and should sit near the\n"
      f"  target level of {100*alpha:.0f}%.\n")
    w("\n  The detector is given no severity information, no fault labels and\n"
      "  no adaptation after commissioning. What it reports is failure of\n"
      "  membership in a region estimated before any degradation occurred.\n")



