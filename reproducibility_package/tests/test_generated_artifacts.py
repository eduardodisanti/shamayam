"""
The coupling between the paper and the generated artefacts.

`make_macros.py` moved the numbers quoted inline in the prose out of the
`.tex` and into `tables/values.tex`. That closes one failure mode -- a
sentence outliving the run it describes -- and opens a smaller one: a macro
used in the prose but never emitted, or emitted but silently orphaned when the
sentence around it was rewritten. The first breaks the build loudly, which is
the intent; the second does not break anything and is exactly the kind of rot
this arrangement was meant to prevent.

These tests are cheap and read files only. They do not run the experiments.
"""

import re
from pathlib import Path

import pytest

PAPER = Path(__file__).resolve().parents[2] / "mssp_draft.tex"
VALUES = Path(__file__).resolve().parents[2] / "tables" / "values.tex"

# Macros emitted by make_macros.py are named by section prefix. Anything in
# the prose matching one of these must come from the generator.
GENERATED_PREFIXES = ("sat", "etoe")

DEF = re.compile(r"\\newcommand\{\\([A-Za-z]+)\}")
USE = re.compile(r"\\([A-Za-z]+)")


def _defined():
    if not VALUES.exists():
        pytest.skip(f"{VALUES} absent; run `python3 make_macros.py`")
    return set(DEF.findall(VALUES.read_text()))


def _paper_body():
    if not PAPER.exists():
        pytest.skip(f"{PAPER} absent")
    text = PAPER.read_text()
    # Strip comments: a macro named only in a commented-out note is neither
    # used nor undefined, and counting it either way would be wrong.
    return "\n".join(re.sub(r"(?<!\\)%.*$", "", ln) for ln in text.splitlines())


def test_every_generated_macro_used_in_the_paper_is_defined():
    """
    An undefined macro is already a LaTeX error, so this test buys one thing
    the compiler does not: it names the offender without a TeX log, and it
    fails in the fast test suite rather than at build time.
    """
    defined, body = _defined(), _paper_body()
    used = {m for m in USE.findall(body)
            if m.startswith(GENERATED_PREFIXES) and m not in ("saturation",)}
    missing = sorted(used - defined)
    assert not missing, (
        f"used in mssp_draft.tex but not emitted by make_macros.py: "
        f"{missing}. Either the generator lost a quantity or the prose "
        f"invented one.")


def test_no_generated_macro_is_orphaned():
    """
    A macro that nothing uses is a quantity the prose once quoted and no
    longer does. It is harmless to LaTeX and misleading to a reader of the
    generator, who will take it for a number the paper reports.
    """
    defined, body = _defined(), _paper_body()
    used = set(USE.findall(body))
    orphans = sorted(defined - used)
    assert not orphans, (
        f"emitted by make_macros.py but unused in mssp_draft.tex: {orphans}. "
        f"Drop them from the generator, or the prose lost a claim.")


def test_the_paper_inputs_the_generated_values():
    body = _paper_body()
    assert re.search(r"\\input\{tables/values\}", body), (
        "mssp_draft.tex does not \\input{tables/values}; the generated "
        "macros would be undefined at build time")


def test_generated_artifacts_declare_their_provenance():
    """
    Every generated file names the run it came from and flags a `--quick` run
    as unquotable. A regenerated artefact that lost its header would be
    indistinguishable from a hand-edited one.
    """
    if not VALUES.exists():
        pytest.skip(f"{VALUES} absent")
    head = VALUES.read_text().splitlines()[:3]
    assert any("GENERATED by" in ln for ln in head)
    assert any("source: results/data.json" in ln for ln in head)


# ---------------------------------------------------------------------
# Figures: generated, included, referenced
#
# The audit found three defects of this kind at once. Two figures were
# produced by make_figures.py on every run and included nowhere -- one of them
# the only visual evidence for a contribution claimed in the Introduction --
# and the central figure of Section 5 was included but never referenced from
# the text. None of it breaks the build: LaTeX is perfectly happy to typeset a
# float nothing points at, and a PDF nobody \includegraphics costs only disk.
# That is precisely why it needs a test.
# ---------------------------------------------------------------------

FIGDIR = Path(__file__).resolve().parents[2] / "figures"
INCLUDE = re.compile(r"\\includegraphics(?:\[[^\]]*\])?\{figures/([A-Za-z0-9_\-]+)\}")
LABEL = re.compile(r"\\label\{(fig:[A-Za-z0-9_\-]+)\}")
FIGREF = re.compile(r"\\ref\{(fig:[A-Za-z0-9_\-]+)\}")


def _generated_figures():
    if not FIGDIR.exists():
        pytest.skip(f"{FIGDIR} absent; run `python3 make_figures.py`")
    names = {p.stem for p in FIGDIR.glob("*.pdf")}
    if not names:
        pytest.skip("no figures generated yet")
    return names


def test_every_generated_figure_is_included_in_the_paper():
    """
    A figure the pipeline produces and the paper never shows is either a
    forgotten result or dead code in the generator. Both are worth knowing.
    """
    generated, body = _generated_figures(), _paper_body()
    included = set(INCLUDE.findall(body))
    orphans = sorted(generated - included)
    assert not orphans, (
        f"generated by make_figures.py but never \\includegraphics'd: "
        f"{orphans}. Either the paper lost a figure or the generator draws "
        f"something nobody reads.")


def test_every_included_figure_is_actually_generated():
    """The converse: an \\includegraphics of a file no generator produces is a
    figure that will silently vanish on a clean checkout."""
    generated, body = _generated_figures(), _paper_body()
    missing = sorted(set(INCLUDE.findall(body)) - generated)
    assert not missing, (
        f"included in the paper but not produced by make_figures.py: "
        f"{missing}")


def test_every_figure_float_is_referenced_from_the_text():
    """
    An unreferenced float is one the reader is never told to look at, and one
    the typesetter is free to place anywhere. Elsevier copy-editing flags it.
    """
    body = _paper_body()
    labelled, referenced = set(LABEL.findall(body)), set(FIGREF.findall(body))
    unreferenced = sorted(labelled - referenced)
    assert not unreferenced, (
        f"figure floats never \\ref-ed from the prose: {unreferenced}")
